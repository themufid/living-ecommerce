const photo = (id: string) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=1600&q=80`

type Draft = Omit<Product, "specs">

function finish(draft: Draft, extras: { label: string; value: string }[] = []): Product {
  return {
    ...draft,
    specs: [
      { label: "SKU", value: draft.sku },
      { label: "Bahan", value: draft.material },
      { label: "Dimensi", value: draft.dimensions },
      { label: "Berat kirim", value: `${draft.weightKg} kg` },
      { label: "Garansi", value: "Rangka 5 tahun, pelapis 1 tahun" },
      ...extras,
    ],
  }
}

const piece = (
  input: Omit<Draft, "modelUrl" | "kind"> & { kind: ProductKind; modelUrl?: string | null },
  extras?: { label: string; value: string }[],
) =>
  finish(
    {
      modelUrl: input.modelUrl ?? null,
      ...input,
    },
    extras,
  )

